#!/usr/bin/env python3
"""Write reproducing.tex, the paper's "Reproducing every result" section, from rows.json.

    python paper/make_tex.py            # rewrite paper/reproducing.tex
    python paper/make_tex.py --check    # exit 1 when the committed file is stale

The table is generated so that it cannot drift from the pins the harness runs.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
ROWS = json.loads((HERE.parent / "rows.json").read_text(encoding="utf-8"))
OUT = HERE / "reproducing.tex"
REPO = "https://github.com/probityai/agent-evidence-vectors"
PIN_KEYS = ("package", "repository", "commit", "commits", "tag", "tags", "corpus_tag",
            "reference", "reader", "script", "converter", "selection", "url", "readers")


def tex(text: str) -> str:
    out = []
    for ch in text:
        if ch in "&%$#_{}":
            out.append("\\" + ch)
        elif ch == "~":
            out.append("\\textasciitilde{}")
        elif ch == "^":
            out.append("\\textasciicircum{}")
        elif ch == "\\":
            out.append("\\textbackslash{}")
        elif ord(ch) > 127:
            out.append({"\u00e1": "\\'a", "\u00f3": "\\'o"}.get(ch, "?"))
        else:
            out.append(ch)
    return "".join(out)


def short(value: Any) -> str:
    if isinstance(value, list):
        return ", ".join(short(v) for v in value)
    text = str(value)
    if len(text) == 40 and all(c in "0123456789abcdef" for c in text):
        return text[:8]
    return text


def pins(row: dict[str, Any]) -> str:
    p = row["pins"]
    return "; ".join(short(p[k]) for k in PIN_KEYS if k in p)


def value_text(value: Any) -> str:
    if isinstance(value, str) and len(value) == 64 and all(c in "0123456789abcdef" for c in value):
        return value[:8]
    if isinstance(value, dict):
        return ", ".join(f"{k} {value_text(v)}" for k, v in value.items())
    if isinstance(value, list):
        return ", ".join(value_text(v) for v in value)
    return str(value)


def expected(row: dict[str, Any]) -> str:
    return "; ".join(f"{name}: {value_text(value)}" for name, value in row["expect"].items())


def render() -> str:
    lines = [
        "% Generated by interop/w3c-v01-appendix/paper/make_tex.py from rows.json; do not edit.",
        "\\section{Reproducing every result}",
        "\\label{sec:reproducing}",
        "Each row of the results-to-inputs table has one pinned rerun in",
        f"\\url{{{REPO}/tree/main/interop/w3c-v01-appendix}}.",
        "The harness fetches each commit by its full SHA and each list attachment by its posted",
        "SHA-256, installs the interpreter and package versions the producer named, runs the posted",
        "command and compares what comes out with the digest posted on the list; nothing is adjusted",
        "to make a row match. \\texttt{python rerun.py <row>} reruns one row and",
        "\\texttt{python rerun.py --all} every row. A scheduled workflow reruns every row weekly and",
        "fails on any digest change. A rerun there is a reproduction in O8's sense: the producer's",
        "implementation run by another operator with the posted outputs visible.",
        "",
        "\\begin{longtable}{@{}p{0.09\\linewidth}p{0.45\\linewidth}p{0.4\\linewidth}@{}}",
        "\\toprule",
        "Row & Pinned inputs & Must come out \\\\",
        "\\midrule",
        "\\endhead",
    ]
    for row_id, row in ROWS["rows"].items():
        lines.append(f"{tex(row_id)} & {tex(pins(row))} & {tex(expected(row))} \\\\")
    lines += ["\\bottomrule", "\\end{longtable}", ""]
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        if OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is stale; run python paper/make_tex.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
