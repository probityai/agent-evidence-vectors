"""matrix.json -> matrix.md and verification.tex. Both are generated; edit matrix.json's sources instead.

    python render.py            # write both
    python render.py --check    # exit 1 when either file differs from what matrix.json gives
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
MATRIX = HERE / "matrix.json"
MD = HERE / "matrix.md"
TEX = HERE / "verification.tex"
TABLE_ROW = {f"W3C-R-{n:03d}": n for n in range(1, 13)} | {"W3C-R-025": 13, "W3C-R-026": 14}
OUTCOME = {"conforms": "conforms", "rejected": "rejected", "cannot-tell": "cannot tell",
           "cannot-read": "cannot read", "not-run": "not run"}


def short(rule: str) -> str:
    """A cited rule in the table's spelling: a numbered row by its number, else as cited."""
    if rule in TABLE_ROW:
        return str(TABLE_ROW[rule])
    if rule.startswith("W3C-R-"):
        return "R" + rule[6:].lstrip("0")
    if rule.startswith("row "):
        return rule[4:]
    return rule


def cell_text(cell: dict[str, Any]) -> str:
    if cell["outcome"] == "rejected":
        return "rejected " + ",".join(short(c) for c in cell["cited"])
    return OUTCOME.get(cell["outcome"], cell["outcome"])


def md(doc: dict[str, Any]) -> str:
    readers = doc["readers"]
    base = [e for e in doc["inputs"] if not e.get("mutant")]
    muts = [e for e in doc["inputs"] if e.get("mutant") and "sha256" in e]
    skipped = [e for e in doc["inputs"] if e.get("not_applicable")]
    out = ["# W3C v0.1 reader conformance matrix", "",
           "Generated by `python render.py` from [`matrix.json`](matrix.json); do not edit by hand.",
           "[README.md](README.md) says how the inputs, mutants and readers are made.", "",
           f"Committed from a run on {doc['platform']}. Producer reruns: "
           + ", ".join(f"{k} {v}" for k, v in doc["producer_reruns"].items()) + ".", "",
           "A cell is `conforms`, `rejected` with the rows the reader cited, `cannot tell` "
           "(a verdict the two spec-text readers can give) or `cannot read`. A numbered row of the "
           "v0.1 rejection table is written by its number (W3C-R-025 is 13, W3C-R-026 is 14); an "
           "unnumbered rule as R and its identifier's number; `shape` is a report that is not "
           "v0.1-shaped; `line N` is the spec line the Kroehl reader cites for an unnumbered rule; "
           "`U-N` is a 0039 label.", "",
           "## Rows of the results table", "",
           "| Row | v0.1 report | Why | Unit | Denominator | Evidence class |", "|---|---|---|---|---|---|"]
    for row, meta in doc["rows"].items():
        denom = meta.get("denominators")
        den = ", ".join(f"{k} {v}" for k, v in denom.items()) if denom else (
            str(meta["denominator"]) if meta.get("denominator") is not None else "-")
        out.append(f"| {row} | {'yes' if meta['yields'] else 'no'} | {meta['why']} | {meta['unit']} "
                   f"| {den} | {meta['class']} |")
    out += ["", "R7 has no cell: its packet records (state, reason) pairs in its own encoding, "
            "not a v0.1 report.", "", "## Reports and readers", "",
            "| Report | " + " | ".join(r["label"] for r in readers) + " |",
            "|---|" + "---|" * len(readers)]
    for e in base:
        out.append(f"| {e['id']} | " + " | ".join(cell_text(doc["cells"][e["id"]][r["id"]]) for r in readers) + " |")
    out += ["", "## Negative controls per reader", "",
            "| Reader | Mutants | Rejected | Conforms | Cannot tell | Cannot read | Target row cited | Rows cited |",
            "|---|---|---|---|---|---|---|---|"]
    for r in readers:
        c = doc["controls"][r["id"]]
        cited = ", ".join(f"{short(k)} x{v}" for k, v in c["rows_cited"].items()) or "-"
        hit = f"{c['target_cited']} of {c['target_comparable']}"
        out.append(f"| {r['label']} | {c['mutants']} | {c['rejected']} | {c['conforms']} | {c['cannot-tell']} "
                   f"| {c['cannot-read']} | {hit} | {cited} |")
    out += ["", "Target row cited counts only mutants whose target the reader's labels can name: "
            "every target for the three reference readers, the numbered rows 1 to 14 for the two "
            "spec-text readers.", "", "### Mutants a reader accepted", ""]
    any_accepted = False
    for r in readers:
        acc = doc["controls"][r["id"]]["accepted"]
        if acc:
            any_accepted = True
            out.append(f"- {r['label']}: " + ", ".join(f"`{a}`" for a in acc))
    if not any_accepted:
        out.append("- none")
    out += ["", "### Positive control", "",
            "A non-ASCII check identity with the root recomputed over the RFC 8785 form, which "
            "writes the character as UTF-8. A reader holding to the jcs-sha256 profile accepts it; "
            "its twin, the root over the ASCII-escaped form, is aimed at W3C-R-020.", "",
            "| Input | " + " | ".join(r["label"] for r in readers) + " |", "|---|" + "---|" * len(readers)]
    for e in muts:
        if e["target"].startswith("none"):
            out.append(f"| {e['id']} | " + " | ".join(cell_text(doc["cells"][e["id"]][r["id"]]) for r in readers) + " |")
    out += ["", "## Every mutant", "",
            "| Mutant | Target | Changed | " + " | ".join(r["label"] for r in readers) + " |",
            "|---|---|---|" + "---|" * len(readers)]
    for e in muts:
        out.append(f"| {e['id']} | {short(e['target']) if not e['target'].startswith('none') else 'none'} "
                   f"| `{e['path']}` | " + " | ".join(cell_text(doc["cells"][e["id"]][r["id"]]) for r in readers) + " |")
    out += ["", "## Targets a report gives no member to aim at", "", "| Report | Mutant | Target | Why |",
            "|---|---|---|---|"]
    for e in skipped:
        out.append(f"| {e['report']} | {e['mutant']} | {short(e['target'])} | {e['not_applicable']} |")
    out += ["", "## Verify commands", "",
            "Each report read by the flag the next release adds; `{release}` is that release.", ""]
    for v in doc["verify_commands"]:
        out.append(f"- {v['row']} {v['report']}: `{v['command']}`")
    return "\n".join(out) + "\n"


def tex_escape(text: str) -> str:
    return (text.replace("\\", r"\textbackslash{}").replace("_", r"\_").replace("&", r"\&")
            .replace("%", r"\%").replace("#", r"\#").replace("{", r"\{").replace("}", r"\}"))


def tex_cell(cell: dict[str, Any]) -> str:
    o = cell["outcome"]
    if o == "conforms":
        return "C"
    if o == "rejected":
        return "R " + tex_escape(",".join(short(c) for c in cell["cited"]))
    return {"cannot-tell": "T", "cannot-read": "N", "not-run": "--"}.get(o, tex_escape(o))


def tex(doc: dict[str, Any]) -> str:
    readers = doc["readers"]
    base = [e for e in doc["inputs"] if not e.get("mutant")]
    out = ["% Generated by interop/w3c-v01-appendix/matrix/render.py from matrix.json; do not edit.",
           r"\providecommand{\aevreadrelease}{\textit{release}}",
           r"\begin{table}[t]", r"\centering", r"\scriptsize",
           r"\begin{tabular}{l" + "l" * len(base) + "}", r"\hline",
           "Reader & " + " & ".join(tex_escape(e["id"]) for e in base) + r" \\", r"\hline"]
    for r in readers:
        out.append(tex_escape(r["label"]) + " & "
                   + " & ".join(tex_cell(doc["cells"][e["id"]][r["id"]]) for e in base) + r" \\")
    out += [r"\hline", r"\end{tabular}",
            r"\caption{Each report rerun from its pins, read by each reader. C conforms; R rejected, "
            r"with the rows cited (a numbered row of the rejection table by its number, an unnumbered "
            r"rule as R and its identifier's number); T cannot tell; N cannot read. R7 has no column: "
            r"its packet is not a v0.1 report.}", r"\label{tab:w3c-matrix}", r"\end{table}", "",
            r"\begin{table}[t]", r"\centering", r"\scriptsize", r"\begin{tabular}{lrrrrrr}", r"\hline",
            r"Reader & Mutants & Rejected & Conforms & Cannot tell & Cannot read & Target cited \\", r"\hline"]
    for r in readers:
        c = doc["controls"][r["id"]]
        out.append(f"{tex_escape(r['label'])} & {c['mutants']} & {c['rejected']} & {c['conforms']} & "
                   f"{c['cannot-tell']} & {c['cannot-read']} & {c['target_cited']}/{c['target_comparable']}" + r" \\")
    out += [r"\hline", r"\end{tabular}",
            r"\caption{Single-field negative controls: every reader on every mutant. Target cited "
            r"counts mutants whose target row the reader named, over those whose target its labels can name.}",
            r"\label{tab:w3c-controls}", r"\end{table}", "",
            r"\begin{itemize}"]
    for v in doc["verify_commands"]:
        cmd = v["command"].replace("{release}", "@@")
        out.append(r"\item " + tex_escape(v["report"]) + r": \texttt{" + tex_escape(cmd).replace("@@", r"\aevreadrelease{}") + "}")
    out.append(r"\end{itemize}")
    return "\n".join(out) + "\n"


def write() -> None:
    doc = json.loads(MATRIX.read_text(encoding="utf-8"))
    MD.write_text(md(doc), encoding="utf-8")
    TEX.write_text(tex(doc), encoding="utf-8")


def stale() -> list[str]:
    doc = json.loads(MATRIX.read_text(encoding="utf-8"))
    return [p.name for p, body in ((MD, md(doc)), (TEX, tex(doc)))
            if not p.is_file() or p.read_text(encoding="utf-8") != body]


if __name__ == "__main__":
    if "--check" in sys.argv:
        bad = stale()
        print("stale: " + ", ".join(bad) if bad else "matrix.md and verification.tex match matrix.json")
        raise SystemExit(1 if bad else 0)
    write()
