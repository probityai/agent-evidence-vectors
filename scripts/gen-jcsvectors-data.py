#!/usr/bin/env python3
"""Copy the RFC 8785 vector files into the jcsvectors Go module and Rust crate.

A Go package can embed only files under its own directory, and ``corpora/`` is a
separate sentinel module that the module proxy never serves. A published crate
likewise holds only files under its own directory. So the Go module and the
crate each carry byte copies of the two corpora, written here and checked by
``scripts/regenerability-gate.py``, which runs this script on a copy of the tree
and refuses any copied file that differs from what it writes. For the crate it
also writes ``src/files.rs``, the list of ``include_bytes!`` entries the crate
embeds, so a file added to a corpus is embedded without a hand edit.

Each package also gets the SHA-256 of every file it embeds (``digests.go`` for
the module, the second column of ``files.rs`` for the crate), and both readers
refuse a file whose bytes do not hash to it. The per-vector digests in
MANIFEST.json cover the a2a vector files only; nothing covered MANIFEST.json
itself or cases.json, whose inputs and refusal cases carry no digest of their
own.

The set copied is exactly what each source declares: the a2a corpus's
MANIFEST.json and every file its ``vectors`` list names, and the byte corpus's
cases.json. Nothing else in either directory is copied.

Usage (from the repository root):
    python3 scripts/gen-jcsvectors-data.py
"""

from __future__ import annotations

import hashlib
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GO_DEST = ROOT / "jcsvectors"
RUST_CRATE = ROOT / "crates" / "jcsvectors"
RUST_DATA = RUST_CRATE / "data"
FILES_RS = RUST_CRATE / "src" / "files.rs"
DIGESTS_GO = GO_DEST / "digests.go"
A2A = "vectors-a2a-jcs-v01"
BYTES = "jcs-byte-vectors"


def sources() -> list[Path]:
    """Every source file to copy, relative to ``corpora/``."""
    manifest = json.loads((ROOT / "corpora" / A2A / "MANIFEST.json").read_text("utf-8"))
    files = [Path(A2A) / "MANIFEST.json"]
    files += [Path(A2A) / entry["path"] for entry in manifest["vectors"]]
    files.append(Path(BYTES) / "cases.json")
    return files


def copy(files: list[Path], dest: Path) -> None:
    for corpus in (A2A, BYTES):
        shutil.rmtree(dest / corpus, ignore_errors=True)
    for rel in files:
        target = dest / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / "corpora" / rel, target)


def sha256(rel: Path) -> str:
    return hashlib.sha256((ROOT / "corpora" / rel).read_bytes()).hexdigest()


def files_rs(files: list[Path]) -> str:
    """The crate's embedded file table: path, SHA-256 and ``include_bytes!``."""
    lines = [
        "// Generated by scripts/gen-jcsvectors-data.py; do not edit.",
        "",
        "/// Every embedded file, at the path its corpus publishes it under, with the",
        "/// SHA-256 of the corpus file it was copied from.",
        "#[rustfmt::skip]",
        "pub(crate) static FILES: &[(&str, &str, &[u8])] = &[",
    ]
    for rel in sorted(files, key=lambda p: p.as_posix()):
        name = rel.as_posix()
        lines.append(f'    ("{name}", "{sha256(rel)}", include_bytes!("../data/{name}")),')
    lines += ["];", ""]
    return "\n".join(lines)


def digests_go(files: list[Path]) -> str:
    """The module's table of the SHA-256 of every embedded file."""
    lines = [
        "// Code generated by scripts/gen-jcsvectors-data.py. DO NOT EDIT.",
        "",
        "package jcsvectors",
        "",
        "// fileDigests pairs the path in FS of every embedded file with the SHA-256",
        "// of the corpus file it was copied from. A slice of pairs rather than a map",
        "// keeps this file as gofmt prints it, with no column alignment to compute.",
        "var fileDigests = [][2]string{",
    ]
    for rel in sorted(files, key=lambda p: p.as_posix()):
        lines.append(f'\t{{"{rel.as_posix()}", "{sha256(rel)}"}},')
    lines += ["}", ""]
    return "\n".join(lines)


def main() -> int:
    files = sources()
    copy(files, GO_DEST)
    copy(files, RUST_DATA)
    FILES_RS.write_text(files_rs(files), encoding="utf-8")
    DIGESTS_GO.write_text(digests_go(files), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
