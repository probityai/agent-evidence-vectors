#!/usr/bin/env python3
"""The corpus registry: one row per corpus, and everything written from it.

corpora/REGISTRY.toml is the one place a corpus is declared: its id (the
published name a CLI, an Action input and a wheel path carry), the directory it
lives in, whether the wheel and the sdist ship it, and its classification on
four axes (record class, domains, standards, failure shapes). The id never
changes; the directory may, because nothing outside joins it to the id.

From the registry this script writes two files, and refuses either when it
differs from what it would write:

  pyproject.toml   the block between the corpus-registry markers: the wheel
                   and sdist include lists, the wheel's directory remapping and
                   its force-included data files
  corpora/README.md  the corpus index, one table per axis, by domain first

  python3 scripts/corpus-registry.py           write both files
  python3 scripts/corpus-registry.py --check   exit 1 when either is stale or
                                               the registry is invalid

The registry is valid when it matches corpora/REGISTRY.schema.json, every id is
unique, every row's directory carries a MANIFEST.json, and the rows name
exactly the corpus directories in the tree: a corpus added without a row, or a
row whose corpus is gone, is refused by name.

Exit 0 when done or current, 1 on a refusal, 2 when the check cannot run.
"""

from __future__ import annotations

import argparse
import json
import sys
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
REGISTRY = Path("corpora/REGISTRY.toml")
SCHEMA = Path("corpora/REGISTRY.schema.json")
INDEX = Path("corpora/README.md")
PYPROJECT = Path("pyproject.toml")
BEGIN = "# BEGIN corpus-registry: generated by scripts/corpus-registry.py from corpora/REGISTRY.toml; do not edit"
END = "# END corpus-registry"

#: The axes the index publishes, in the order its tables appear. Domain first:
#: it is the view a newcomer asks for.
AXES: list[tuple[str, str]] = [
    ("domains", "By domain"),
    ("record_class", "By record class"),
    ("standards", "By standard"),
    ("shapes", "By failure shape"),
]


def load(repo: Path) -> dict:
    with open(repo / REGISTRY, "rb") as source:
        return tomllib.load(source)


def corpus_dirs_on_disk(repo: Path) -> dict[str, str]:
    """Every directory holding a corpus, by id, with its repository-relative path.

    A corpus is a directory named ``vectors`` or ``vectors-*`` that carries a
    MANIFEST.json, at the repository root or directly under ``corpora/``.
    """
    found: dict[str, str] = {}
    for parent in (repo, repo / "corpora"):
        if not parent.is_dir():
            continue
        for child in sorted(parent.iterdir()):
            name = child.name
            if (name == "vectors" or name.startswith("vectors-")) and (child / "MANIFEST.json").is_file():
                rel = child.relative_to(repo).as_posix()
                if name in found:
                    found[name] = found[name] + " and " + rel
                else:
                    found[name] = rel
    return found


def schema_errors(registry: dict, repo: Path) -> list[str]:
    try:
        import jsonschema
    except ImportError:
        return ["jsonschema is not importable; run under `uv run --locked --extra dev`"]
    schema = json.loads((repo / SCHEMA).read_text(encoding="utf-8"))
    validator = jsonschema.Draft202012Validator(schema)
    return [
        "{}: {}".format("/".join(str(p) for p in error.absolute_path) or "(root)", error.message)
        for error in sorted(validator.iter_errors(registry), key=lambda e: list(map(str, e.absolute_path)))
    ]


def registry_errors(registry: dict, repo: Path) -> list[str]:
    errors = schema_errors(registry, repo)
    if errors:
        return errors
    rows = registry["corpus"]
    seen: set[str] = set()
    for row in rows:
        if row["id"] in seen:
            errors.append(f"{row['id']}: listed twice")
        seen.add(row["id"])
        path = repo / row["path"]
        if Path(row["path"]).name != row["id"]:
            errors.append(f"{row['id']}: path {row['path']} does not end in the id")
        if not (path / "MANIFEST.json").is_file():
            errors.append(f"{row['id']}: {row['path']}/MANIFEST.json does not exist")
        if row["wheel"] and not row["sdist"]:
            errors.append(f"{row['id']}: shipped in the wheel but not in the sdist the wheel is built from")
    ids = [row["id"] for row in rows]
    if ids != sorted(ids, key=lambda i: (i != "vectors", i)):
        errors.append("rows are not sorted by id with `vectors` first")
    on_disk = corpus_dirs_on_disk(repo)
    for name, rel in sorted(on_disk.items()):
        if " and " in rel:
            errors.append(f"{name}: two directories carry this id: {rel}")
        elif name not in seen:
            errors.append(f"{name}: corpus directory {rel} has no row in {REGISTRY}")
    for row in rows:
        if row["id"] in on_disk and on_disk[row["id"]] != row["path"]:
            errors.append(f"{row['id']}: row says {row['path']}, the corpus is at {on_disk[row['id']]}")
    for entry in registry["data"]:
        if not (repo / entry["src"]).is_file():
            errors.append(f"data {entry['src']}: file does not exist")
    return errors


def toml_string(value: str) -> str:
    return json.dumps(value)


def toml_list(items: list[str], indent: str = "    ") -> list[str]:
    return ["["] + [f"{indent}{toml_string(item)}," for item in items] + ["]"]


def pyproject_block(registry: dict) -> str:
    build = registry["build"]
    wheel_rows = [row for row in registry["corpus"] if row["wheel"]]
    sdist_rows = [row for row in registry["corpus"] if row["sdist"]]
    package_src, package_dest = build["package"]["src"], build["package"]["wheel"]
    lines = [BEGIN, "[tool.hatch.build.targets.wheel]"]
    only = toml_list([package_src] + [row["path"] for row in wheel_rows])
    lines.append("only-include = " + only[0])
    lines += only[1:]
    # A corpus directory carries its generators and checkers beside its data;
    # the wheel carries the data and the packaged readers only.
    exclude = toml_list(build["exclude"] + [f"{row['path']}/**/*.py" for row in wheel_rows])
    lines.append("exclude = " + exclude[0])
    lines += exclude[1:]
    lines += ["", "[tool.hatch.build.targets.wheel.sources]"]
    lines.append(f"{toml_string(package_src)} = {toml_string(package_dest)}")
    for row in wheel_rows:
        lines.append(f"{toml_string(row['path'])} = {toml_string(package_dest + '/corpora/' + row['id'])}")
    lines += ["", "[tool.hatch.build.targets.wheel.force-include]"]
    for entry in registry["data"]:
        for note in entry["purpose"].splitlines():
            lines.append(f"# {note}".rstrip())
        lines.append(f"{toml_string(entry['src'])} = {toml_string(package_dest + '/' + entry['wheel'])}")
    lines += ["", "[tool.hatch.build.targets.sdist]"]
    sdist = toml_list(
        build["sdist_extra"]
        + [package_src]
        + [entry["src"] for entry in registry["data"]]
        + [row["path"] for row in sdist_rows]
    )
    lines.append("only-include = " + sdist[0])
    lines += sdist[1:]
    sdist_exclude = toml_list(build["exclude"])
    lines.append("exclude = " + sdist_exclude[0])
    lines += sdist_exclude[1:]
    lines.append(END)
    return "\n".join(lines) + "\n"


def pyproject_text(current: str, registry: dict) -> str:
    start = current.find(BEGIN)
    end = current.find(END)
    if start < 0 or end < start:
        raise SystemExit(f"{PYPROJECT} has no corpus-registry markers")
    end = current.index("\n", end) + 1
    return current[:start] + pyproject_block(registry) + current[end:]


def index_text(registry: dict) -> str:
    rows = registry["corpus"]
    out = [
        "# Corpus index",
        "",
        "<!-- Generated by scripts/corpus-registry.py from REGISTRY.toml; do not edit. -->",
        "",
        f"{len(rows)} corpora. Each is named by its id: pass the id to the command line "
        "(`agent-evidence-vectors --corpus <id>`) or to the Action (`corpus: <id>`). "
        "`agent-evidence-vectors --list-corpora --format json` prints the ids for a CI matrix. "
        "The same corpus appears under every value it carries, so a corpus sits in more than one row of a table.",
        "",
    ]
    for axis, heading in AXES:
        out += [f"## {heading}", "", "| Value | Corpora |", "| --- | --- |"]
        values: dict[str, list[dict]] = {}
        for row in rows:
            carried = row[axis] if isinstance(row[axis], list) else [row[axis]]
            for value in carried or ["none"]:
                values.setdefault(value, []).append(row)
        for value in sorted(values):
            links = ", ".join(f"[{r['id']}]({link(r)})" for r in values[value])
            out.append(f"| {value} | {links} |")
        out.append("")
    out += ["## Every corpus", "", "| Id | Title | What it checks |", "| --- | --- | --- |"]
    for row in rows:
        out.append(f"| [{row['id']}]({link(row)}) | {row['title']} | {row['summary']} |")
    return "\n".join(out) + "\n"


def link(row: dict) -> str:
    """A row's directory relative to corpora/, where the index lives."""
    path = Path(row["path"])
    return path.name + "/" if path.parent == Path("corpora") else "../" + path.as_posix() + "/"


def main() -> int:
    parser = argparse.ArgumentParser(description="Check the corpus registry and write the files derived from it.")
    parser.add_argument("--check", action="store_true", help="refuse a stale file or an invalid registry")
    parser.add_argument("--repo", type=Path, default=REPO, help=argparse.SUPPRESS)
    args = parser.parse_args()
    repo = args.repo
    try:
        registry = load(repo)
    except (OSError, tomllib.TOMLDecodeError) as error:
        print(f"FAIL: {REGISTRY} cannot be read: {error}", file=sys.stderr)
        return 2
    errors = registry_errors(registry, repo)
    if errors:
        for error in errors:
            print(f"FAIL: {error}", file=sys.stderr)
        return 1
    current = (repo / PYPROJECT).read_text(encoding="utf-8")
    wanted = {PYPROJECT: pyproject_text(current, registry), INDEX: index_text(registry)}
    stale = []
    for path, text in wanted.items():
        target = repo / path
        if not target.is_file() or target.read_text(encoding="utf-8") != text:
            if args.check:
                stale.append(path)
            else:
                target.write_text(text, encoding="utf-8")
                print(f"wrote {path}")
    if stale:
        for path in stale:
            print(f"FAIL: {path} is not what corpora/REGISTRY.toml writes; run python3 scripts/corpus-registry.py", file=sys.stderr)
        return 1
    print(f"corpus registry: {len(registry['corpus'])} corpora, {len(registry['data'])} data files; derived files current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
