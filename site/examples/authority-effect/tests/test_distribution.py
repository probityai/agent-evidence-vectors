@pytest.mark.parametrize(
    "name",
    [
        "../escaped.py",
        "/authority_effect/reader.py",
        "authority_effect/./alias.py",
        "authority_effect//alias.py",
        "authority_effect\\alias.py",
        "another_package/reader.py",
        "authority_effect/reader.py",
    ],
)
def test_unsafe_unknown_and_duplicate_wheel_members_refuse(installation, name):
    _, wheel, _ = installation
    if name == "authority_effect/reader.py":
        with pytest.warns(UserWarning, match="Duplicate name"):
            with ZipFile(wheel, "a") as archive:
                archive.writestr(name, b"duplicate reader")
    else:
        with ZipFile(wheel, "a") as archive:
            archive.writestr(name, b"unselected member")
    with pytest.raises(InputError, match="unsafe, duplicate or unsupported"):
        check(installation)


@pytest.mark.parametrize("name", ["authority_effect/reader.py", "authority_effect/linked/"])
def test_symlink_wheel_member_refuses_even_when_regular_payload_bytes_match(installation, name):
    _, wheel, _ = installation
    with ZipFile(wheel) as archive:
        files = {member: archive.read(member) for member in archive.namelist()}
    # The reader twin keeps exactly the regular file's bytes; the directory
    # twin would otherwise disappear under ZIP's trailing-slash filtering.
    files.setdefault(name, b"fixtures/")
    with ZipFile(wheel, "w") as archive:
        for member, content in files.items():
            info = ZipInfo(member)
            if member == name:
                info.create_system = 3
                info.external_attr = (stat.S_IFLNK | 0o777) << 16
            archive.writestr(info, content)
    with pytest.raises(InputError, match="symlink member"):
        check(installation)


@pytest.mark.parametrize(
    "omitted", ["authority_effect/reader.py", METADATA + "WHEEL", METADATA + "RECORD"]
)
def test_missing_required_wheel_member_refuses(installation, omitted):
    _, wheel, _ = installation
    with ZipFile(wheel) as archive:
        files = {name: archive.read(name) for name in archive.namelist() if name != omitted}
    with ZipFile(wheel, "w") as archive:
        for name, content in files.items():
            archive.writestr(name, content)
    with pytest.raises(InputError, match="lacks the required"):
        check(installation)


