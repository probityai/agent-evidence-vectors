"""Use real wheel and installation files to exercise package identity refusals."""

import stat
import zipfile
from importlib.metadata import PathDistribution
from pathlib import Path
from zipfile import ZipFile, ZipInfo

import pytest

from authority_effect.distribution import installed_payload
from authority_effect.reader import InputError

METADATA = "probity_authority_effect_cases-0.1.0.dist-info/"
LAUNCHER = "probity_authority_effect_cases-0.1.0.data/scripts/probity-authority-effect-cases"


@pytest.fixture
def installation(tmp_path):
    root = tmp_path / "installed"
    files = {
        "authority_effect/reader.py": b"# finite test reader\n",
        "authority_effect/fixtures/case.json": b"{}\n",
        METADATA + "METADATA": b"Name: probity-authority-effect-cases\nVersion: 0.1.0\n",
        METADATA + "WHEEL": b"Wheel-Version: 1.0\n",
        METADATA + "RECORD": b"installer may rewrite this record\n",
        LAUNCHER: b"#!/bin/sh\nexit 0\n",
    }
    for name, content in files.items():
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
    (root / METADATA / "direct_url.json").write_text('{"archive_info":{}}')
    (root / "bin").mkdir()
    (root / "bin/probity-authority-effect-cases").write_bytes(files[LAUNCHER])
    wheel = tmp_path / "selected.whl"
    with ZipFile(wheel, "w") as archive:
        for name, content in files.items():
            archive.writestr(name, content)
    distribution = PathDistribution(root / METADATA)
    return root, wheel, distribution


def check(installation):
    root, wheel, distribution = installation
    return installed_payload(
        wheel,
        distribution,
        root / "authority_effect/reader.py",
        launcher_file=root / "bin/probity-authority-effect-cases",
    )


def test_exact_payload_ignores_only_installer_metadata_and_generated_bytecode(installation):
    root, wheel, _ = installation
    cache = root / "authority_effect/__pycache__/reader.cpython-313.pyc"
    cache.parent.mkdir()
    cache.write_bytes(b"generated bytecode")
    (root / METADATA / "RECORD").write_text("rewritten installer record")
    report = check(installation)
    assert len(report["files"]) == 5
    assert report["wheelSha256"]
    assert all(row["path"] != METADATA + "RECORD" for row in report["files"])
    assert wheel.exists()


def test_real_zip_backed_distribution_is_outside_filesystem_identity_profile(installation):
    root, wheel, _ = installation
    assert check(installation)["files"]
    with ZipFile(wheel) as archive:
        distribution = PathDistribution(zipfile.Path(archive, METADATA))
        assert distribution.version == "0.1.0"
        with pytest.raises(InputError, match="root is not a filesystem path"):
            installed_payload(wheel, distribution, root / "authority_effect/reader.py")


def test_uv_cache_is_recorded_as_an_installer_addition(installation):
    root, _, _ = installation
    cache = root / METADATA / "uv_cache.json"
    cache.write_bytes(b'{"timestamp":{"secs_since_epoch":1},"commit":null}')
    report = check(installation)
    assert len(report["files"]) == 5
    row = next(
        row
        for row in report["installerGeneratedMetadata"]
        if row["path"] == METADATA + "uv_cache.json"
    )
    assert row["bytes"] == cache.stat().st_size
    assert row["sha256"]
    assert all(row["path"] != METADATA + "uv_cache.json" for row in report["files"])


def test_wheel_owned_cache_metadata_still_requires_exact_bytes(installation):
    root, wheel, _ = installation
    name = METADATA + "uv_cache.json"
    content = b'{"wheelOwned":true}'
    with ZipFile(wheel, "a") as archive:
        archive.writestr(name, content)
    (root / name).write_bytes(content)
    report = check(installation)
    assert any(row["path"] == name for row in report["files"])
    assert all(row["path"] != name for row in report["installerGeneratedMetadata"])
    (root / name).write_bytes(b'{"wheelOwned":false}')
    with pytest.raises(InputError, match="bytes differ"):
        check(installation)


def test_installed_record_must_remain_present_after_rewriting(installation):
    root, _, _ = installation
    record = root / METADATA / "RECORD"
    record.write_bytes(b"different installer-created record bytes\n")
    assert check(installation)["files"]
    record.unlink()
    with pytest.raises(InputError, match="metadata file population differs"):
        check(installation)


def test_console_bytes_and_symlink_require_selected_wheel(installation):
    root, _, _ = installation
    launcher = root / "bin/probity-authority-effect-cases"
    original = launcher.read_bytes()
    launcher.write_bytes(original + b"# changed launcher\n")
    with pytest.raises(InputError, match="bytes differ"):
        check(installation)
    launcher.unlink()
    with pytest.raises(InputError, match="bytes differ"):
        check(installation)
    alternate = root / "bin/alternate"
    alternate.write_bytes(original)
    launcher.symlink_to(alternate)
    with pytest.raises(InputError, match="bytes differ"):
        check(installation)


@pytest.mark.parametrize("name", ["authority_effect/reader.py", METADATA + "METADATA"])
def test_changed_or_missing_installed_bytes_refuse(installation, name):
    root, _, _ = installation
    with (root / name).open("ab") as stream:
        stream.write(b"changed despite matching direct-url metadata")
    with pytest.raises(InputError, match="bytes differ"):
        check(installation)
    (root / name).unlink()
    with pytest.raises(InputError):
        check(installation)


def test_installed_version_property_is_not_needed_for_exact_payload(installation):
    root, wheel, _ = installation

    class UnparsedDistribution(PathDistribution):
        @property
        def version(self):
            raise AssertionError("installed metadata parsed before byte identity")

    distribution = UnparsedDistribution(root / METADATA)
    selected = root, wheel, distribution
    assert check(selected)["files"]
    (root / METADATA / "METADATA").unlink()
    with pytest.raises(InputError, match="metadata file population differs"):
        check(selected)


