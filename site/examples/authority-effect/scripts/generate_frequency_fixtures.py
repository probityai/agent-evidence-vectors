"""Author the explicit twelve-cell supplied-claim table and invalid Boolean inputs."""

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "authority_effect/frequency_fixtures"
PROFILE = "probity.frequency-supplied-claims/v1"
# These answers are explicit reference labels; the reader is never invoked here.
TABLE: list[tuple[bool, bool, str | None, str, str, str]] = [
    (True, True, "v1", "AUTHORIZED", "REPORTED", "MATCHES_REQUEST"),
    (True, True, "v2", "AUTHORIZED", "REPORTED", "DIFFERS_FROM_REQUEST"),
    (True, True, None, "AUTHORIZED", "REPORTED", "NOT_ESTABLISHED"),
    (True, False, "v1", "AUTHORIZED", "NOT_REPORTED", "MATCHES_REQUEST"),
    (True, False, "v2", "AUTHORIZED", "NOT_REPORTED", "DIFFERS_FROM_REQUEST"),
    (True, False, None, "AUTHORIZED", "NOT_REPORTED", "NOT_ESTABLISHED"),
    (False, True, "v1", "DENIED", "REPORTED", "MATCHES_REQUEST"),
    (False, True, "v2", "DENIED", "REPORTED", "DIFFERS_FROM_REQUEST"),
    (False, True, None, "DENIED", "REPORTED", "NOT_ESTABLISHED"),
    (False, False, "v1", "DENIED", "NOT_REPORTED", "MATCHES_REQUEST"),
    (False, False, "v2", "DENIED", "NOT_REPORTED", "DIFFERS_FROM_REQUEST"),
    (False, False, None, "DENIED", "NOT_REPORTED", "NOT_ESTABLISHED"),
]
INVALID: list[tuple[str, object]] = [
    ("false-string", "false"),
    ("true-string", "true"),
    ("zero", 0),
    ("one", 1),
    ("null", None),
    ("array", []),
    ("object", {}),
    ("float", 0.0),
]


def encoded(value: dict) -> bytes:
    # Ordinary JSON retains invalid floating tokens for the refusal controls.
    return (json.dumps(value, sort_keys=True, indent=2) + "\n").encode()


def cases() -> dict[str, bytes]:
    files: dict[str, bytes] = {}
    rows: list[dict] = []

    def add(name: str, value: dict, expected: dict | str) -> None:
        raw = encoded(value | {"profile": PROFILE, "id": name})
        files[name + ".json"] = raw
        rows.append(
            {
                "id": name,
                "path": name + ".json",
                "sha256": hashlib.sha256(raw).hexdigest(),
                "expected": expected,
            }
        )

    for authorized, reported, observation, decision, report, effect in TABLE:
        name = "-".join(
            (decision.lower(), report.lower().replace("_", "-"), effect.lower().replace("_", "-"))
        )
        add(
            name,
            {
                "authorized": authorized,
                "executionReported": reported,
                "requestedEffect": "v1",
                "observation": observation,
            },
            {
                "suppliedDecision": decision,
                "completionReport": report,
                "requestedEffectComparison": effect,
            },
        )
    base = {
        "authorized": True,
        "executionReported": True,
        "requestedEffect": "v1",
        "observation": "v1",
    }
    for field in ("authorized", "executionReported"):
        for suffix, invalid in INVALID:
            name = "invalid-" + ("decision" if field == "authorized" else "report") + "-" + suffix
            add(name, base | {field: invalid}, "REFUSED")
    files["manifest.json"] = encoded(
        {"profile": PROFILE, "total": len(rows), "comparisonCells": len(TABLE), "cases": rows}
    )
    return files


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = cases()
    if args.check:
        actual = {str(path.relative_to(ROOT)): path.read_bytes() for path in ROOT.rglob("*.json")}
        if actual != outputs:
            raise SystemExit("supplied-claims fixture regeneration differs")
    else:
        ROOT.mkdir(parents=True, exist_ok=True)
        for name, raw in outputs.items():
            (ROOT / name).write_bytes(raw)
    print(f"supplied-claims generated bytes match: {len(outputs)} files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
