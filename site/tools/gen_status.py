#!/usr/bin/env python3
"""Generate src/status.md from data/lab-register.json, data/open-cells.toml and data/filed-runs.toml.

    python3 tools/gen_status.py            write src/status.md
    python3 tools/gen_status.py --check    fail if src/status.md differs from what the data gives

The page states, for every retained Lab record, which claims stand ESTABLISHED,
CONTRADICTED or NOT_ESTABLISHED, at which evidence class, under which operation class,
and lists the open cells of the mechanism-by-property grid. Both rules below are written
on the page, so a reader can check every number against the register.
"""

from __future__ import annotations

import json
import re
import sys
import tomllib
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from run_browser import destination, records, text  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
REGISTER = ROOT / "data" / "lab-register.json"
CELLS = ROOT / "data" / "open-cells.toml"
FILED = ROOT / "data" / "filed-runs.toml"
OUT = ROOT / "src" / "status.md"
HEADER = "<!-- GENERATED by tools/gen_status.py from data/lab-register.json, data/open-cells.toml and data/filed-runs.toml; edit the data, not this file. -->\n"

# Per-claim result in the register -> the verdict this page prints.
VERDICT = {
    "pass": "ESTABLISHED",
    "fail": "CONTRADICTED",
    "unknown": "UNKNOWN",
    "not-exercised": "NOT_ESTABLISHED",
    "out-of-scope": "NOT_ESTABLISHED",
}
RESULTS = ("pass", "fail", "unknown", "not-exercised", "out-of-scope")
RESULT_LABEL = {
    "pass": "ESTABLISHED",
    "fail": "CONTRADICTED",
    "unknown": "unknown, observation unresolved",
    "not-exercised": "NOT_ESTABLISHED, not exercised",
    "out-of-scope": "NOT_ESTABLISHED, out of scope",
}

PROBITY, AUTHOR, INDEPENDENT = "Probity-operated", "author-operated", "independently operated"
CLASSES = (PROBITY, AUTHOR, INDEPENDENT)
# Roles that name who operated the run, in the spellings the register uses.
OPERATOR_ROLES = ("runner", "atlasOperator", "fixtureOperator", "historicalRunner", "diagnosticRunner", "atlasReplay")
INDEPENDENCE_ROLES = ("independentOperation", "independentOperator")


def verdict(result: str) -> str:
    """The page verdict for a supported raw result; other tokens are errors."""
    if result not in VERDICT:
        raise ValueError(f"unknown claim result {result!r}")
    return VERDICT[result]


def operation_class(roles: dict[str, str]) -> str:
    """Exactly one operation class for a record, from its own roles.

    Independently operated only when an independence role is exactly "established";
    otherwise Probity-operated when an operator role names Probity; otherwise
    author-operated when an operator role is present. A record with no operator role
    is an error, never a default."""
    if any(roles.get(k) == "established" for k in INDEPENDENCE_ROLES):
        return INDEPENDENT
    named = [roles[k] for k in OPERATOR_ROLES if k in roles]
    if not named:
        raise ValueError("record names no operator role")
    if any(v.startswith("Probity") for v in named):
        return PROBITY
    return AUTHOR


def cell(value: str) -> str:
    return text(value)


def table(header: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def tested(record_id: str) -> str:
    """A few words for what a record tested: its identifier without the date, as words."""
    return re.sub(r"-\d{4}-\d{2}-\d{2}$", "", record_id).replace("-", " ")


def tally(recs: list[dict]) -> tuple[dict[str, Counter], Counter]:
    by_class: dict[str, Counter] = {c: Counter() for c in CLASSES}
    nrec: Counter = Counter()
    for r in recs:
        oc = operation_class(r["roles"])
        nrec[oc] += 1
        for claim in r["claimResults"]:
            verdict(claim["result"])
            by_class[oc][claim["result"]] += 1
    return by_class, nrec


def totals_table(by_class: dict[str, Counter], nrec: Counter) -> str:
    rows = []
    for res in RESULTS:
        counts = [by_class[c][res] for c in CLASSES]
        rows.append([f"{RESULT_LABEL[res]} (`{res}`)", *map(str, counts), f"**{sum(counts)}**"])
    claims = [sum(by_class[c].values()) for c in CLASSES]
    rows.append(["claim results", *map(str, claims), f"**{sum(claims)}**"])
    rows.append(["records", *(str(nrec[c]) for c in CLASSES), f"**{sum(nrec.values())}**"])
    return table(["verdict", *CLASSES, "all"], rows)


def record_table(recs: list[dict]) -> str:
    rows = []
    for r in recs:
        c = Counter(verdict(x["result"]) for x in r["claimResults"])
        oos = sum(1 for x in r["claimResults"] if x["result"] == "out-of-scope")
        n = str(c["NOT_ESTABLISHED"]) + (f" ({oos} out of scope)" if oos else "")
        links = f"[report]({destination(r['report'])}), [provenance]({destination(r['provenance'])})"
        rows.append([f"`{cell(r['id'])}`", cell(tested(r["id"])), f"`{cell(r['evidenceClaim'])}`",
                     str(c["ESTABLISHED"]), str(c["CONTRADICTED"]), n, str(c["UNKNOWN"]),
                     operation_class(r["roles"]), f"`{cell(r['reviewState'])}`", links])
    return table(["record", "tested", "evidence class", "E", "C", "N", "U", "operation", "review state", "files"], rows)


def cell_name(c: dict) -> str:
    return f"{cell(c['mechanism_title'])} x {cell(c['property_title'])}"


def source(c: dict) -> str:
    return f"[source]({c['url']}) ({c['basis']})"


def start_list(cells: dict[tuple[str, str], dict], starts: list[dict]) -> str:
    out = []
    for s in sorted(starts, key=lambda s: s["rank"]):
        c = cells[(s["mechanism"], s["property"])]
        out.append(f"{s['rank']}. **{cell_name(c)}** ({cell(c['property_question'])}?). "
                   f"Limit: \"{cell(c['words'])}\" {source(c)}. Take it: {cell(s['passing_case'])}.")
    return "\n".join(out)


def cell_table(cells: dict[tuple[str, str], dict], starts: list[dict]) -> str:
    featured = {(s["mechanism"], s["property"]) for s in starts}
    rows = [[cell(c["mechanism_title"]), cell(c["property_title"]), f"\"{cell(c['words'])}\"", source(c)]
            for key, c in cells.items() if key not in featured]
    return table(["mechanism", "property", "limit, in the Atlas's words", "source"], rows)


RUN_KEYS = ("id", "link", "target", "pins", "operated_by", "lab_rerun", "shows", "open")


def filed_runs(data: dict) -> list[dict]:
    """The filed runs, each with exactly the declared keys; a missing or extra key is an error."""
    runs = data.get("run", [])
    ids = [r.get("id") for r in runs]
    if len(ids) != len(set(ids)):
        raise ValueError("duplicate filed run id")
    for r in runs:
        if set(r) != set(RUN_KEYS) or not all(isinstance(r[k], str) and r[k] for k in RUN_KEYS):
            raise ValueError(f"filed run {r.get('id')!r} must carry exactly {RUN_KEYS} as nonempty strings")
    return runs


def runs_table(runs: list[dict]) -> str:
    rows = [[f"[`{cell(r['id'])}`]({r['link']})", cell(r["target"]), cell(r["pins"]), cell(r["operated_by"]),
             cell(r["lab_rerun"]), cell(r["shows"]), cell(r["open"])] for r in runs]
    return table(["run", "cell or case", "pins", "operated by", "Lab rerun", "what it shows", "still open"], rows)


def render(register: dict, open_cells: dict, filed: dict | None = None) -> str:
    runs = filed_runs(filed or {})
    recs = records(register)
    by_class, nrec = tally(recs)
    cells = {(c["mechanism"], c["property"]): c for c in open_cells["cell"]}
    if len(cells) != len(open_cells["cell"]):
        raise ValueError("duplicate open cell")
    starts = open_cells.get("start", [])
    for s in starts:
        if (s["mechanism"], s["property"]) not in cells:
            raise ValueError("a start entry names no open cell")
    n_claims = sum(len(r["claimResults"]) for r in recs)
    return "\n".join([
        "---",
        'title: "Claim status"',
        'subtitle: "What stands, on what evidence, operated by whom, and the open cells"',
        f'status: "Generated from the Lab register ({len(recs)} records, {n_claims} claim results) and {len(cells)} open cells."',
        'description: "Every retained Lab claim result as ESTABLISHED, CONTRADICTED, NOT_ESTABLISHED or unknown, with its evidence class, operator and files, and the open mechanism-by-property cells."',
        "---",
        "",
        HEADER.rstrip("\n"),
        "",
        "Claim results in the [Lab register](lab/register.json), counted by verdict and by who operated the run.",
        "A claim stands only at its record's evidence class"
        + ("; no record here was independently operated." if nrec[INDEPENDENT] == 0 else "."),
        "",
        totals_table(by_class, nrec),
        "",
        "## Verification, host use and paid use",
        "",
        "A verification or reproduction checks selected inputs with a named reader. Host use needs separate evidence that the host keeps and runs the integration.",
        "The [Packslip observation](runs.html#record-packslip-dsse-host-ci-2026-10-11) retains one historical successful host test step and a published development dependency. Its regression was author-contributed; the Atlas metadata reading is Probity-operated.",
        "Neither a retained test nor a development dependency establishes a production deployment, an independently observed effect or paid use. Those claims need their own evidence.",
        "Registry download counts measure requests. They do not count users, maintained integrations or revenue.",
        "",
        "## Open cells: take one",
        "",
        "An open cell is a mechanism and a property where the mechanism's own documentation, or the text that defines it, says it cannot establish the property. Start with these:",
        "",
        start_list(cells, starts),
        "",
        "To take a cell, [open an Evidence run issue](https://github.com/probityai/agent-evidence/issues/new?template=evidence-run.yml) naming it. Listing a cell makes no claim about who closes it; a run that does is recorded in the Lab like any other.",
        "",
        *([
            "## Runs filed against cells and cases",
            "",
            "Runs filed as Evidence runs or in a case thread. They are not register records and carry no claim results, so the totals above do not count them. Each row says who operated the run and what the Lab reran itself.",
            "",
            runs_table(runs),
            "",
        ] if runs else []),
        "## Every record",
        "",
        "E, C and N count a record's ESTABLISHED, CONTRADICTED and NOT_ESTABLISHED claim results. U counts `unknown`: an observation remains unresolved. The evidence class and review state are the record's own fields.",
        "",
        record_table(recs),
        "",
        f"## Every open cell ({len(cells)})",
        "",
        f"The {len(starts)} cells above, then the rest. Each limit is the Atlas's wording; \"states the limit\" means the source page says it, and \"states the scope\" means the page states the function the limit bounds.",
        "",
        cell_table(cells, starts),
        "",
        "## How this page is derived",
        "",
        "Verdicts: `pass` is ESTABLISHED, `fail` is CONTRADICTED, and `not-exercised` and `out-of-scope` are NOT_ESTABLISHED, with out-of-scope results labelled. A verdict holds only at the record's evidence class.",
        "`unknown` stays distinct: the observation cannot settle the claim. It is neither a failed claim nor a check that was not exercised, and it is counted separately.",
        "",
        f"Operation class, first match wins, from the record's own roles: **{INDEPENDENT}** only when `independentOperation` or `independentOperator` is exactly `established`; **{PROBITY}** when an operator role (`runner`, `atlasOperator`, `fixtureOperator`, `historicalRunner`, `diagnosticRunner` or `atlasReplay`) names Probity; otherwise **{AUTHOR}**, where an operator role names the author of the fixture or software under test.",
        "",
        "The page is regenerated by `python3 tools/gen_status.py`, and `python3 tools/build.py --check` fails when it is stale. Open cells come from `data/open-cells.toml`, written by `tools/export_open_cells.py`, which keeps a cell only when an excerpt of its source page was found there.",
        "",
    ])


def main() -> int:
    register = json.loads(REGISTER.read_text(encoding="utf-8"))
    open_cells = tomllib.loads(CELLS.read_text(encoding="utf-8"))
    filed = tomllib.loads(FILED.read_text(encoding="utf-8"))
    out = render(register, open_cells, filed)
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != out:
            print("src/status.md is out of date with its data: run python3 tools/gen_status.py")
            return 1
        print("src/status.md matches its data")
        return 0
    OUT.write_text(out, encoding="utf-8")
    print("wrote src/status.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
