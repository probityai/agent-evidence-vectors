#!/usr/bin/env python3
"""Generate src/board.md from data/board.toml and data/board-results.json.

    python3 tools/gen_board.py            write src/board.md
    python3 tools/gen_board.py --check    fail if src/board.md differs from what the data gives

The page prints one verdict table per corpus family: each outside implementation at its pinned
commit and at the head of its default branch, pass, fail or not runnable, with the vectors that
failed and the run that produced the verdict. Implementations with no entry point that takes the
corpus are listed with the tree that was read. Edit the data, not the page.
"""
from __future__ import annotations

import json
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BOARD = ROOT / "data" / "board.toml"
RESULTS = ROOT / "data" / "board-results.json"
OUT = ROOT / "src" / "board.md"
HEADER = "<!-- GENERATED by tools/gen_board.py from data/board.toml and data/board-results.json; edit the data, not this file. -->\n"


def short(sha: str) -> str:
    return sha[:8]


def cell(record: dict | None, family: str, pin: str, repo: str) -> str:
    if record is None:
        return "not yet run"
    entry = next((f for f in record["families"] if f["family"] == family), None)
    if entry is None:
        return "not yet run"
    verdict = entry["verdict"]
    counts = f" ({entry['passed']} of {entry['vectors']})" if "passed" in entry else ""
    same = " (the pin)" if record["source_sha"] == pin else ""
    sub = entry.get("declared_subset")
    extra = f"; inside its declared {sub['rule']} subset **{sub['passed']} of {sub['vectors']}**" if sub else ""
    link = f"[`{short(record['source_sha'])}`](https://github.com/{repo}/commit/{record['source_sha']})"
    return f"**{verdict}**{counts}{extra} at {link}{same}"


def failing(record: dict | None, family: str) -> str:
    if record is None:
        return ""
    entry = next((f for f in record["families"] if f["family"] == family), None)
    if entry is None:
        return ""
    if entry["verdict"] == "not runnable":
        return entry.get("why", "")
    rows = entry.get("failing", [])
    if not rows:
        return "none"
    if "id" in rows[0]:
        ids = [r["id"] for r in rows]
        return f"{len(ids)}: " + ", ".join(f"`{i}`" for i in ids[:14]) + (", and more" if len(ids) > 14 else "")
    proposed = sum(1 for r in rows if r.get("proposed"))
    lead = f"{len(rows)} members, {proposed} of them under clauses the corpus marks proposed because the verifier's contract text leaves them open: "
    return lead + "; ".join(r["detail"].split(" ", 1)[1] if " " in r["detail"] else r["detail"] for r in rows)[:600]


def run_link(records: list[dict]) -> str:
    urls = {r["run_url"] for r in records if r and r.get("run_url")}
    return ", ".join(f"[run]({u})" for u in sorted(urls))


def render(board: dict, results: dict) -> str:
    meta = board["meta"]
    by_key = {(r["id"], r["slot"]): r for r in results["results"]}
    implementations = board["implementation"]
    scored = [i for i in implementations if i["status"] == "scored"]
    lines = [
        "---",
        'title: "Conformance board"',
        'subtitle: "Every outside implementation we can run, scored against one pinned corpus"',
        f'status: "Generated from the board data; corpus agent-evidence-vectors {meta["vectors_version"]}, results of {results["generated"]}."',
        'description: "Pass, fail or not runnable for each outside implementation against the pinned agent-evidence-vectors corpus, at its pinned commit and at the head of its default branch, with the failing vectors and the run that produced each verdict."',
        "---",
        "",
        HEADER.rstrip("\n"),
        "",
        f"Each row runs an outside implementation's own code on the saved records of [agent-evidence-vectors](https://pypi.org/project/agent-evidence-vectors/) {meta['vectors_version']}. Our CI re-runs every score on a schedule and whenever the implementation's default branch moves, so a verdict at a new upstream commit appears here without anyone asking for it. Pass means the harness executed every vector and none failed. Fail means it executed every vector and some failed. Not runnable means the implementation could not be run to completion on that corpus, and the cell says why.",
        "",
        "A verdict is kept only when the same adapter first passes two controls: the corpus's reference canonicalizer must pass every vector, and a deliberately wrong canonicalizer must fail the ten vectors the corpus expects it to fail. For the anchor stream the control is that the runner reproduces the corpus's own recording of a published verifier tag on every member. A failure in a row below therefore comes from the implementation, not from the adapter or the harness. Each implementation's declared scope is printed beside its verdict. A vector outside the scope an implementation declares is a difference of profile, and the row says so rather than hiding it.",
        "",
    ]
    for key, family in board["family"].items():
        rows = [i for i in scored if any(r["family"] == key for r in i["run"])]
        if not rows:
            continue
        lines += [
            f"## {family['title']}",
            "",
            f"Corpus `{family['corpus']}`, target `{family['target']}`, {family['vectors']} vectors. {family['what']}",
            "",
            "| implementation | declared scope | at the pinned commit | at the default-branch head | failing vectors at the pin | runs |",
            "|---|---|---|---|---|---|",
        ]
        for item in rows:
            pinned, head = by_key.get((item["id"], "pinned")), by_key.get((item["id"], "head"))
            lines.append(
                f"| [{item['name']}](https://github.com/{item['repo']}) | {item['declared_scope']} | "
                f"{cell(pinned, key, item['pin'], item['repo'])} | {cell(head, key, item['pin'], item['repo'])} | "
                f"{failing(pinned, key)} | {run_link([pinned, head])} |"
            )
        lines.append("")
    stuck = [i for i in implementations if i["status"] == "not-runnable"]
    held = [i for i in implementations if i["status"] == "held"]
    lines += [
        "## No entry point that takes the corpus",
        "",
        "These implementations were read at the pinned commit and have no command that can run a corpus of ours. The row names the tree that was read.",
        "",
        "| implementation | pinned commit | tree read | why it is not runnable |",
        "|---|---|---|---|",
    ]
    for item in stuck:
        lines.append(f"| [{item['name']}](https://github.com/{item['repo']}) | [`{short(item['pin'])}`](https://github.com/{item['repo']}/commit/{item['pin']}) | [tree]({item['url_checked']}) | {item['reason']} |")
    lines += [
        "",
        "## Not scored on this board",
        "",
        "The board's publication rules hold these implementations out of the tables above. They are listed so the board covers the field it names.",
        "",
        "| implementation | pinned commit |",
        "|---|---|",
    ]
    for item in held:
        lines.append(f"| [{item['name']}](https://github.com/{item['repo']}) | [`{short(item['pin'])}`](https://github.com/{item['repo']}/commit/{item['pin']}) |")
    lines += [
        "",
        "## Verified by Probity",
        "",
        "Verified by Probity (github.com/probityai/probity). A score on this board is our CI running an outside implementation against the pinned corpus. It is not the badge. The badge is granted to a project, never self-declared, recorded in the grant ledger of agent-evidence-vectors, and re-checked at every release; the rules are on the [Verified by Probity page](https://github.com/probityai/agent-evidence-vectors/blob/main/docs/VERIFIED-BADGE.md). No row on this board carries it.",
        "",
        "To run the same corpus in your own CI, pin the package:",
        "",
        "```bash",
        f"uv add agent-evidence-vectors=={meta['vectors_version']}",
        f"pip install agent-evidence-vectors=={meta['vectors_version']}",
        "```",
        "",
        "## Add an implementation",
        "",
        "Add one entry to [`data/board.toml`](https://github.com/probityai/agent-evidence-vectors/blob/main/site/data/board.toml): the repository, a pinned commit, the file and function that take the corpus, and its declared scope. The [workflow](https://github.com/probityai/agent-evidence-vectors/blob/main/.github/workflows/site-board.yml) scores it on the next run. To run one row by hand, see [`tools/run_board.py`](https://github.com/probityai/agent-evidence-vectors/blob/main/site/tools/run_board.py). The packaged corpus runs in your own CI with the [agent-evidence-vectors Action](https://github.com/probityai/agent-evidence-vectors).",
        "",
        "Each verdict has a row in the [claim ledger](claims.html).",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    board = tomllib.loads(BOARD.read_text(encoding="utf-8"))
    results = json.loads(RESULTS.read_text(encoding="utf-8"))
    text = render(board, results)
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            sys.stderr.write("src/board.md is not what data/board.toml and data/board-results.json give; run python3 tools/gen_board.py\n")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
