#!/usr/bin/env python3
"""Generate src/atlas.md from data/atlas.toml and templates/atlas.md.in.

    python3 tools/gen_atlas.py            write src/atlas.md
    python3 tools/gen_atlas.py --check    fail if src/atlas.md differs from what the data gives

The data file is the only place an atlas fact is written. Every table on the page
is rendered from it, so a fact changes in one place and the page follows.
"""

from __future__ import annotations

import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "atlas.toml"
TEMPLATE = ROOT / "templates" / "atlas.md.in"
OUT = ROOT / "src" / "atlas.md"
HEADER = "<!-- GENERATED by tools/gen_atlas.py from data/atlas.toml; edit the data, not this file. -->\n"

LABEL_CLASS = {"published": "published", "open": "open", "proposed": "proposed",
               "draft": "draft", "individual draft": "draft"}


def cell(text: str) -> str:
    return text.replace("|", "\\|")


def table(header: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(cell(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def label(text: str) -> str:
    return f"[{text}]{{.label .{LABEL_CLASS[text]}}}"


def entry_status(e: dict) -> str:
    parts = [e["status"]] if e.get("status") else []
    if "stars" in e:
        parts.append(f"{e['stars']:,} stars")
    return "; ".join(parts)


def corpus_link(c: dict) -> str:
    """The corpus directory at its pinned commit, so the row names the exact bytes counted."""
    repo = c.get("repo", "probityai/agent-evidence-vectors")
    return f"[`{c['dir']}`](https://github.com/{repo}/tree/{c['commit']}/{c.get('path', c['dir'])})"


VERSION_SOURCES = ("tag:", "pypi:", "crate:")


def check_artifact_versions(artifacts: list[dict]) -> None:
    """Refuse an artifact whose shown release does not carry the version tools/rederive.py reads.

    `version` is the exact value the re-derive reader returns for `version_from`, so the
    page, the weekly re-derive and the claim ledger read one value instead of three copies.
    """
    for a in artifacts:
        if "version" not in a or "version_from" not in a:
            raise SystemExit(f"artifact {a['name']} has no version or version_from")
        if not a["version_from"].startswith(VERSION_SOURCES):
            raise SystemExit(f"artifact {a['name']}: version_from must start with one of {VERSION_SOURCES}")
        if a["version"] not in a["release"]:
            raise SystemExit(f"artifact {a['name']}: release {a['release']!r} does not show version {a['version']!r}")


def render(d: dict) -> str:
    check_artifact_versions(d["artifact"])
    layers, entries, mechs = d["layer"], d["entry"], d["mechanism"]
    names = {l["id"]: f"{i}. {l['name']}" for i, l in enumerate(layers, 1)}

    layer_table = table(
        ["family", "the question it answers", "a working instance establishes", "it cannot establish on its own"],
        [[names[l["id"]], l["short_question"], l["short_establishes"], l["short_cannot"]] for l in layers])

    mech_rows = []
    for m in mechs:
        where = names.get(m["layer"], "the open cell")
        mech_rows.append([m["name"], where, m["writer"], m["establishes"], m["cannot"]])
    mechanism_table = table(["mechanism", "family", "writer", "establishes", "cannot establish"], mech_rows)

    sections = []
    for i, l in enumerate(layers, 1):
        rows = [[f"[{e['name']}]({e['url']})", entry_status(e)] for e in entries if e["layer"] == l["id"]]
        nxt = layers[i]["name"] if i < len(layers) else layers[0]["name"]
        seam_title = f"Seam to family {i + 1}" if i < len(layers) else "Seam back to family 1"
        sections.append("\n\n".join([
            f"## {i}. {l['name']}",
            f"Question\n:   {l['question']}\n\nEstablishes\n:   {l['establishes']}\n\n"
            f"Cannot establish\n:   {l['cannot']}",
            table(["project or standard", f"status read 2026-09-27; stars read {d['meta']['stars_read']}"], rows),
            f"{seam_title} ({nxt.lower()})\n:   {l['seam']}",
        ]))

    artifact_table = table(
        ["artifact", "family", "release and read time; status label", "what it does", "what it does not do"],
        [[f"[{a['name']}]({a['url']})", a["layers"], f"{a['release']}; read {a.get('read', '2026-09-27')} {label(a['label'])}", a["does"], a["does_not"]]
         for a in d["artifact"]])

    corpora = d["corpus"]
    release = d["meta"]["corpus_release"]
    in_release = [c for c in corpora if c["pin"] == release]
    corpus_table = table(
        ["corpus", "pinned at", "members", "split", "what it tests"],
        [[corpus_link(c), f"{c['pin']} (`{c['commit'][:7]}`)", str(c["members"]), c["split"], c["tests"]]
         for c in corpora])

    contribution_table = table(
        ["where", "what", f"state, read {d['meta']['contributions_read']}"],
        [[f"[{c['where']}]({c['url']})", c["what"], f"{label(c['label'])} {c['state']}"] for c in d["contribution"]])

    listing_table = table(
        ["listing", "what", f"state, read {d['meta']['listings_read']}"],
        [[f"[{x['where']}]({x['url']})", x["what"], label(x["label"])] for x in d["listing"]])

    values = {
        "version": d["meta"]["version"],
        "read_window": d["meta"]["read_window"],
        "stars_read": d["meta"]["stars_read"],
        "n_layers": str(len(layers)),
        "n_entries": str(len(entries)),
        "n_mechanisms": str(len(mechs)),
        "corpus_release": release,
        "corpus_commit": d["meta"]["corpus_commit"][:7],
        "corpus_read": d["meta"]["corpus_read"],
        "n_vectors": f"{sum(c['members'] for c in in_release):,}",
        "n_corpora": str(len(in_release)),
        "n_other_corpora": str(len(corpora) - len(in_release)),
        "layer_table": layer_table,
        "mechanism_table": mechanism_table,
        "layer_sections": "\n\n".join(sections),
        "artifact_table": artifact_table,
        "corpus_table": corpus_table,
        "contribution_table": contribution_table,
        "listing_table": listing_table,
    }
    text = TEMPLATE.read_text(encoding="utf-8")
    for key, value in values.items():
        text = text.replace("{{" + key + "}}", value)
    if "{{" in text:
        raise SystemExit("unfilled placeholder in the atlas template")
    # Keep the YAML front matter first, as pandoc requires; the header follows it.
    front, sep, body = text.partition("\n---\n")
    return front + sep + HEADER + body


def main() -> int:
    d = tomllib.loads(DATA.read_text(encoding="utf-8"))
    text = render(d)
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("src/atlas.md is out of date with data/atlas.toml: run python3 tools/gen_atlas.py")
            return 1
        print("src/atlas.md matches data/atlas.toml")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote src/atlas.md: {len(d['layer'])} families, {len(d['entry'])} entries, "
          f"{len(d['mechanism'])} mechanisms, {len(d['corpus'])} corpora")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
